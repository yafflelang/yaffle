/**
 * The Go conformance harness: a main package that runs cases through the generated root API and
 * writes raw results (JSON, bytes, errors) for the adapter to judge.
 */
import { goStr } from "./code.ts";
import { DEFAULT_RUNTIME } from "./index.ts";

/** The Go names of a root's API. */
export interface HarnessRoot {
  name: string;
  type: string;
  parse: string;
  serialize: string;
  toJSON: string;
  fromJSON: string;
  optionsFromJSON: string;
  /** `ViewX` and `MaterializeXView` (view mode, docs/CONFORMANCE.md §7), when generated. */
  view?: string | undefined;
  materialize?: string | undefined;
}

function viewEntry(r: HarnessRoot): string {
  if (!r.view || !r.materialize) return "";
  return `
		view: func(data []byte, args []byte, strict bool) (any, func() ([]byte, error), error) {
			o, err := gen.${r.optionsFromJSON}(args)
			if err != nil {
				return nil, nil, err
			}
			o.Strict = strict
			x, err := gen.${r.view}(data, o)
			if err != nil {
				return nil, nil, err
			}
			v, err := gen.${r.materialize}(x)
			if err != nil {
				return nil, nil, err
			}
			return v, func() ([]byte, error) { return x.Commit(yaffle.CommitOptions{}) }, nil
		},`;
}

export function harnessSource(roots: HarnessRoot[], pkgImport: string): string {
  const entries = roots
    .map(
      r => `	${goStr(r.name)}: {
		parse: func(data []byte, args []byte, strict bool) (any, error) {
			o, err := gen.${r.optionsFromJSON}(args)
			if err != nil {
				return nil, err
			}
			o.Strict = strict
			v, err := gen.${r.parse}(data, o)
			return v, err
		},
		serialize: func(v any, args []byte, strict bool) ([]byte, error) {
			o, err := gen.${r.optionsFromJSON}(args)
			if err != nil {
				return nil, err
			}
			o.Strict = strict
			return gen.${r.serialize}(v.(*gen.${r.type}), o)
		},
		toJSON: func(v any) ([]byte, error) { return gen.${r.toJSON}(v.(*gen.${r.type})) },
		fromJSON: func(data []byte) (any, error) {
			v, err := gen.${r.fromJSON}(data)
			return v, err
		},${viewEntry(r)}
	},`
    )
    .join("\n");
  // gofmt order: by import path.
  const imports = (
    [
      [DEFAULT_RUNTIME, ""],
      [pkgImport, "gen "]
    ] as const
  )
    .toSorted((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
    .map(([path, alias]) => `\t${alias}${goStr(path)}`)
    .join("\n");
  return `// Code generated by the yaffle Go conformance adapter. DO NOT EDIT.

package main

import (
	"bufio"
	"bytes"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"runtime/debug"
	"strconv"

${imports}
)

type api struct {
	parse     func(data []byte, args []byte, strict bool) (any, error)
	serialize func(v any, args []byte, strict bool) ([]byte, error)
	toJSON    func(v any) ([]byte, error)
	fromJSON  func(data []byte) (any, error)
	view      func(data []byte, args []byte, strict bool) (any, func() ([]byte, error), error)
}

var roots = map[string]api{
${entries}
}

type caseIn struct {
	Name      string          \`json:"name"\`
	Root      string          \`json:"root"\`
	Args      json.RawMessage \`json:"args"\`
	Hex       *string         \`json:"hex"\`
	File      *string         \`json:"file"\`
	JSON      json.RawMessage \`json:"json"\`
	Input     json.RawMessage \`json:"input"\`
	Roundtrip string          \`json:"roundtrip"\`
	Strict    bool            \`json:"strict"\`
	ErrPhase  string          \`json:"errorPhase"\`
	Mode      string          \`json:"mode"\`
}

type errOut struct {
	Phase   string \`json:"phase"\`
	Code    string \`json:"code"\`
	Path    []any  \`json:"path"\`
	Offset  int    \`json:"offset"\`
	Message string \`json:"message"\`
}

type result struct {
	Name     string  \`json:"name"\`
	Phase    string  \`json:"phase"\`
	JSONFile string  \`json:"jsonFile,omitempty"\`
	Bytes    *string \`json:"bytes,omitempty"\`
	OutLen   int     \`json:"outLen"\`
	Equal    *bool   \`json:"equal,omitempty"\`
	DiffAt   int     \`json:"diffAt"\`
	Error    *errOut \`json:"error,omitempty"\`
	Panic    string  \`json:"panic,omitempty"\`
	Message  string  \`json:"message,omitempty"\`
}

const maxHex = 1 << 20

func errorOf(err error, phase string) *errOut {
	if e, ok := yaffle.AsError(err); ok {
		path := e.Path
		if path == nil {
			path = []any{}
		}
		return &errOut{Phase: phase, Code: string(e.Code), Path: path, Offset: e.Offset, Message: e.Error()}
	}
	return &errOut{Phase: phase, Code: "INTERNAL", Path: []any{}, Offset: -1, Message: err.Error()}
}

func run(c caseIn, out string, idx int) (res result) {
	res = result{Name: c.Name, DiffAt: -1}
	defer func() {
		if p := recover(); p != nil {
			res.Panic = fmt.Sprintf("%v\\n%s", p, debug.Stack())
		}
	}()
	a, ok := roots[c.Root]
	if !ok {
		res.Message = "unknown root " + c.Root
		return
	}
	args := []byte(c.Args)
	if len(args) == 0 {
		args = []byte("{}")
	}
	var data []byte
	if c.Hex != nil {
		b, err := hex.DecodeString(*c.Hex)
		if err != nil {
			res.Message = "bad hex"
			return
		}
		data = b
	} else if c.File != nil {
		b, err := os.ReadFile(*c.File)
		if err != nil {
			res.Message = err.Error()
			return
		}
		data = b
	}
	setBytes := func(b []byte) {
		res.OutLen = len(b)
		if len(b) <= maxHex {
			h := hex.EncodeToString(b)
			res.Bytes = &h
		}
		if data != nil {
			eq := bytes.Equal(b, data)
			res.Equal = &eq
			if !eq {
				i := 0
				for i < len(b) && i < len(data) && b[i] == data[i] {
					i++
				}
				res.DiffAt = i
			}
		}
	}
	if len(c.Input) > 0 {
		res.Phase = "serialize"
		v, err := a.fromJSON(c.Input)
		if err != nil {
			res.Error = errorOf(err, "serialize")
			return
		}
		b, err := a.serialize(v, args, c.Strict)
		if err != nil {
			res.Error = errorOf(err, "serialize")
			return
		}
		setBytes(b)
		return
	}
	res.Phase = "parse"
	if c.Mode == "view" {
		runView(c, a, data, args, out, idx, &res, setBytes)
		return
	}
	v, err := a.parse(data, args, c.Strict)
	if err != nil {
		res.Error = errorOf(err, "parse")
		return
	}
	j, err := a.toJSON(v)
	if err != nil {
		res.Error = errorOf(err, "parse")
		return
	}
	file := filepath.Join(out, strconv.Itoa(idx)+".json")
	if err := os.WriteFile(file, j, 0o644); err != nil {
		res.Message = err.Error()
		return
	}
	res.JSONFile = file
	rt := c.Roundtrip
	if c.ErrPhase == "serialize" {
		rt = "json"
	}
	if rt == "false" {
		return
	}
	res.Phase = "serialize"
	var input any
	if rt == "value" {
		input = v
	} else {
		src := []byte(c.JSON)
		if len(src) == 0 {
			src = j
		}
		input, err = a.fromJSON(src)
		if err != nil {
			res.Error = errorOf(err, "serialize")
			return
		}
	}
	b, err := a.serialize(input, args, c.Strict)
	if err != nil {
		res.Error = errorOf(err, "serialize")
		return
	}
	setBytes(b)
	return
}

// runView: read every field through the view, then commit it with no edits.
func runView(c caseIn, a api, data, args []byte, out string, idx int, res *result, setBytes func([]byte)) {
	if a.view == nil {
		res.Message = "not implemented: views are not generated"
		return
	}
	v, commit, err := a.view(data, args, c.Strict)
	if err != nil {
		res.Error = errorOf(err, "parse")
		return
	}
	j, err := a.toJSON(v)
	if err != nil {
		res.Error = errorOf(err, "parse")
		return
	}
	file := filepath.Join(out, strconv.Itoa(idx)+".json")
	if err := os.WriteFile(file, j, 0o644); err != nil {
		res.Message = err.Error()
		return
	}
	res.JSONFile = file
	if c.Roundtrip == "false" {
		return
	}
	res.Phase = "serialize"
	b, err := commit()
	if err != nil {
		res.Error = errorOf(err, "serialize")
		return
	}
	setBytes(b)
}

func main() {
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	var cases []caseIn
	if err := json.Unmarshal(raw, &cases); err != nil {
		panic(err)
	}
	out := os.Args[2]
	f, err := os.Create(filepath.Join(out, "results.jsonl"))
	if err != nil {
		panic(err)
	}
	w := bufio.NewWriter(f)
	enc := json.NewEncoder(w)
	for i, c := range cases {
		if err := enc.Encode(run(c, out, i)); err != nil {
			panic(err)
		}
	}
	if err := w.Flush(); err != nil {
		panic(err)
	}
	if err := f.Close(); err != nil {
		panic(err)
	}
}
`;
}
