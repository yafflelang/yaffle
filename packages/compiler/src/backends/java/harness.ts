/**
 * The conformance harness: a Java program generated per case directory that runs every case
 * through the generated root API and writes what it observed (canonical JSON, output bytes,
 * errors) for the TypeScript side of the adapter to judge.
 *
 * Input (JSON): `[{ name, cls, args, bytes: hex | { file }, json, input, roundtrip, strict,
 * errorPhase, view }]`. Output: one JSON file per case in the results directory, `<index>.json`:
 * `{ json?, out?, outLen?, outEqual?, diffAt?, error?: { phase, code, path, offset, message },
 * exception? }`.
 */
import { str } from "./code.ts";

export interface HarnessRoot {
  /** Java class of the root struct. */
  cls: string;
  /** Root of an async schema (parseAsync/serializeAsync only). */
  async: boolean;
}

export const HARNESS_CLASS = "yaffle.harness.Harness";

/** One `case "Cls": return new RootApi() {…};` of the harness's root switch. */
function rootApi(pkg: string, r: HarnessRoot, optionsName: string): string {
  const C = pkg ? `${pkg}.${r.cls}` : r.cls;
  const opts = `${C}.${optionsName}.fromJson(args)`;
  const o = `strict ? ${opts}.strict(true) : ${opts}`;
  const parse = r.async ? `join(${C}.parseAsync(bytes, ${o}))` : `${C}.parse(bytes, ${o})`;
  const serialize = r.async
    ? `join(${C}.serializeAsync((${C}) value, ${o}))`
    : `${C}.serialize((${C}) value, ${o})`;
  return `
      case ${str(r.cls)}:
        return new RootApi() {
          @Override
          public Object parse(byte[] bytes, Object args, boolean strict) {
            return ${parse};
          }

          @Override
          public byte[] serialize(Object value, Object args, boolean strict) {
            return ${serialize};
          }

          @Override
          public Object toJson(Object value) {
            return ${C}.toJson((${C}) value);
          }

          @Override
          public Object fromJson(Object json) {
            return ${C}.fromJson(json);
          }

          @Override
          public StructView view(byte[] bytes, Object args, boolean strict) {
            return ${C}.view(bytes, ${o});
          }

          @Override
          public AsyncView<?> viewAsync(AsyncSource source, Object args, boolean strict) {
            return ${C}.viewAsync(source, ${o});
          }
        };`;
}

export function harnessSource(pkg: string, roots: HarnessRoot[], optionsName: string): string {
  const dot = HARNESS_CLASS.lastIndexOf(".");
  return `// Generated by the yaffle conformance adapter. Do not edit.
package ${HARNESS_CLASS.slice(0, dot)};

import org.yafflelang.runtime.AsyncSource;
import org.yafflelang.runtime.AsyncView;
import org.yafflelang.runtime.Hex;
import org.yafflelang.runtime.Json;
import org.yafflelang.runtime.StructView;
import org.yafflelang.runtime.ViewRead;
import org.yafflelang.runtime.YaffleException;
import java.io.BufferedWriter;
import java.io.IOException;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.nio.channels.AsynchronousFileChannel;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CompletionException;

/** Runs conformance cases through the generated API. */
public final class ${HARNESS_CLASS.slice(dot + 1)} {
  private ${HARNESS_CLASS.slice(dot + 1)}() {}

  /** Outputs larger than this are compared here but not sent back as hex. */
  private static final int MAX_HEX = 1 << 20;

  private interface RootApi {
    Object parse(byte[] bytes, Object args, boolean strict);

    byte[] serialize(Object value, Object args, boolean strict);

    Object toJson(Object value);

    Object fromJson(Object json);

    StructView view(byte[] bytes, Object args, boolean strict);

    AsyncView<?> viewAsync(AsyncSource source, Object args, boolean strict);
  }

  private static <T> T join(CompletableFuture<T> f) {
    try {
      return f.join();
    } catch (CompletionException e) {
      if (e.getCause() instanceof RuntimeException r) throw r;
      throw e;
    }
  }

  private static RootApi api(String cls) {
    switch (cls) {${roots.map(r => rootApi(pkg, r, optionsName)).join("\n")}
      default:
        return null;
    }
  }

  private static byte[] load(Object bytes) throws IOException {
    if (bytes instanceof String s) return Hex.decode(s);
    final Map<?, ?> m = (Map<?, ?>) bytes;
    return Files.readAllBytes(Path.of((String) m.get("file")));
  }

  private static void out(Map<String, Object> res, byte[] out, byte[] expected) {
    res.put("outLen", (long) out.length);
    if (out.length <= MAX_HEX) res.put("out", Hex.encode(out));
    if (expected != null) {
      res.put("outEqual", Arrays.equals(out, expected));
      int i = 0;
      while (i < out.length && i < expected.length && out[i] == expected[i]) i++;
      res.put("diffAt", (long) i);
    }
  }

  private static Map<String, Object> run(Map<?, ?> cs) throws IOException {
    final Map<String, Object> res = new LinkedHashMap<>();
    final RootApi api = api((String) cs.get("cls"));
    if (api == null) {
      res.put("exception", "no root class " + cs.get("cls"));
      return res;
    }
    final Object args = cs.get("args");
    final boolean strict = Boolean.TRUE.equals(cs.get("strict"));
    final Object input = cs.get("input");
    final byte[] bytes = cs.get("bytes") == null ? null : load(cs.get("bytes"));
    String phase = input != null ? "serialize" : "parse";
    try {
      if (input != null) {
        out(res, api.serialize(api.fromJson(input), args, strict), bytes);
        return res;
      }
      final Object errorPhase = cs.get("errorPhase");
      if (Boolean.TRUE.equals(cs.get("view"))) {
        // View mode (docs/CONFORMANCE.md §7): read every field through the view, then commit it
        // without edits. Files are opened as async random-access sources.
        if (cs.get("bytes") instanceof Map<?, ?> fm) {
          try (AsynchronousFileChannel ch =
              AsynchronousFileChannel.open(Path.of((String) fm.get("file")), StandardOpenOption.READ)) {
            final AsyncView<?> av = api.viewAsync(AsyncSource.of(ch), args, strict);
            res.put("json", Json.normalize(api.toJson(join(av.materialize()))));
            if ("parse".equals(errorPhase)) return res;
            if (Boolean.FALSE.equals(cs.get("roundtrip"))) return res;
            phase = "serialize";
            out(res, join(av.commit()), bytes);
            return res;
          }
        }
        final StructView v = api.view(bytes, args, strict);
        res.put("json", Json.normalize(api.toJson(ViewRead.materialize(v))));
        if ("parse".equals(errorPhase)) return res;
        if (Boolean.FALSE.equals(cs.get("roundtrip"))) return res;
        phase = "serialize";
        out(res, v.commit(), bytes);
        return res;
      }
      final Object value = api.parse(bytes, args, strict);
      final Object json = Json.normalize(api.toJson(value));
      res.put("json", json);
      if ("parse".equals(errorPhase)) return res;
      Object rt = cs.containsKey("roundtrip") ? cs.get("roundtrip") : Boolean.TRUE;
      if ("serialize".equals(errorPhase)) rt = "json";
      if (Boolean.FALSE.equals(rt)) return res;
      phase = "serialize";
      final Object in =
          "value".equals(rt) ? value : api.fromJson(cs.get("json") != null ? cs.get("json") : json);
      out(res, api.serialize(in, args, strict), bytes);
    } catch (YaffleException e) {
      final Map<String, Object> err = new LinkedHashMap<>();
      err.put("phase", phase);
      err.put("code", e.code().name());
      err.put("path", new ArrayList<Object>(e.path()));
      err.put("offset", e.offset());
      err.put("message", e.getMessage());
      res.put("error", err);
    } catch (RuntimeException | StackOverflowError | OutOfMemoryError e) {
      final StringWriter sw = new StringWriter();
      e.printStackTrace(new PrintWriter(sw));
      res.put("exception", phase + ": " + sw);
    }
    return res;
  }

  public static void main(String[] argv) throws Exception {
    final List<?> cases =
        (List<?>) Json.parse(Files.readString(Path.of(argv[0]), StandardCharsets.UTF_8));
    final Path dir = Path.of(argv[1]);
    Files.createDirectories(dir);
    for (int i = 0; i < cases.size(); i++) {
      final Map<String, Object> res = run((Map<?, ?>) cases.get(i));
      try (BufferedWriter w = Files.newBufferedWriter(dir.resolve(i + ".json"), StandardCharsets.UTF_8)) {
        Json.write(res, w);
      }
    }
  }
}
`;
}
