/**
 * Java source files: one final class per struct (fields, reader, writer, JSON, views, and for
 * exported structs the root API), one enum (or record, for open enums) per IR enum, and one
 * sealed interface per union type.
 */
import type { IrEnum, IrRoot, IrStruct } from "../../ir/index.ts";
import { Code, enumConst, ident, longLit, str } from "./code.ts";
import { ClassCtx, type ExternRef } from "./ctx.ts";
import { ExprCompiler } from "./expr.ts";
import { JsonEmitter } from "./json.ts";
import type { Model, UnionInfo } from "./model.ts";
import { ReadEmitter } from "./read.ts";
import { ViewClassEmitter } from "./viewclass.ts";
import { derivedFrom, layoutReads } from "./views.ts";
import { WriteEmitter } from "./write.ts";

export interface JavaFile {
  /** Simple class name. */
  name: string;
  contents: string;
}

/** Assembles a file: header, package, imports (scanned from the body), body. */
function assemble(model: Model, cls: ClassCtx, src: string, body: string): string {
  const out: string[] = [`// Generated by yaffle from ${src}. Do not edit.`];
  if (model.pkg) out.push(`package ${model.pkg};`, "");
  const imports = model.importsFor(body, cls.used);
  if (imports.length) out.push(...imports, "");
  out.push(body);
  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

function javadoc(s: string): string {
  return s.replace(/\*\//g, "*&#47;").replace(/\n/g, "\n * ");
}

/** The emitters of one struct's class. */
interface Emitters {
  cls: ClassCtx;
  x: ExprCompiler;
  reader: ReadEmitter;
  writer: WriteEmitter;
  json: JsonEmitter;
}

export class ClassEmitter {
  readonly model: Model;
  readonly externs: Record<string, ExternRef>;

  constructor(model: Model, externs: Record<string, ExternRef>) {
    this.model = model;
    this.externs = externs;
  }

  // ── structs ─────────────────────────────────────────────────────────────────

  /** A struct's class; `root` adds the root API (parse, serialize, views, …). */
  struct(s: IrStruct, root: IrRoot | undefined): JavaFile {
    const model = this.model;
    const name = model.className(s.id);
    const cls = new ClassCtx(model, this.externs);
    const x = new ExprCompiler(model);
    const e: Emitters = {
      cls,
      x,
      reader: new ReadEmitter(model, x, cls),
      writer: new WriteEmitter(model, x, cls),
      json: new JsonEmitter(model, cls)
    };
    // Elements of arrays that derives or layouts read can't be patched in place.
    const derived = derivedFrom(s);
    const relayout = layoutReads(s);
    e.reader.elementEncoder = (st, t, le, field) =>
      field && (derived.has(field) || relayout.has(field))
        ? undefined
        : e.writer.elementEncoder(st, t, le);
    const methods = new Code();
    e.reader.emitStruct(methods, s);
    methods.line("");
    e.writer.emitStruct(methods, s);
    methods.line("");
    e.json.emitStruct(methods, s);
    methods.line("");
    e.reader.emitStruct(methods, s, true);
    if (root) {
      methods.line("");
      this.rootApi(methods, s, root, e);
    }
    const viewCode = new Code();
    const vce = new ViewClassEmitter(model, cls, e.writer);
    vce.emitInfo(viewCode, s);
    viewCode.line("");
    vce.emitView(viewCode, s);

    const body = new Code();
    body.line(s.doc ? `/** ${javadoc(s.doc)} */` : `/** The yaffle struct {@code ${s.name}}. */`);
    body.block(`public final class ${name} implements ${cls.use("YValue")}`, () => {
      const infos = [...model.fieldInfos(s).values()];
      for (const fi of infos) {
        body.line(`${fi.hidden ? "" : "public "}${fi.type} ${fi.java};`);
        if (fi.raw) {
          body.line(
            `/** Raw value of the one-way transform {@code ${fi.name}} (written; in JSON). */`
          );
          body.line(`public ${fi.raw.type} ${fi.raw.java};`);
        }
        if (fi.present) {
          body.line(
            `/** {@code ${fi.name}}'s branch was taken (a null value is then {@code null} in JSON). */`
          );
          body.line(`boolean ${fi.present};`);
        }
      }
      if (infos.length) body.line("");
      for (const l of cls.hoistedLines) body.line(l);
      if (cls.hoistedLines.length) body.line("");
      body.line(`public ${name}() {}`);
      body.line("");
      body.line(`/** Canonical JSON of this value (what {@code ==} compares). */`);
      body.line("@Override");
      body.block("public Object toJsonValue()", () =>
        body.line(`return toJson(this, new ${cls.use("ToJsonCtx")}(), "");`)
      );
      body.line("");
      body.block(`${name} copy()`, () => {
        body.line(`final ${name} $c = new ${name}();`);
        for (const fi of infos) {
          body.line(`$c.${fi.java} = this.${fi.java};`);
          if (fi.raw) body.line(`$c.${fi.raw.java} = this.${fi.raw.java};`);
          if (fi.present) body.line(`$c.${fi.present} = this.${fi.present};`);
        }
        body.line("return $c;");
      });
      body.line("");
      body.append(methods);
      body.line("");
      body.append(viewCode);
    });
    return { name, contents: assemble(model, cls, s.module, body.toString()) };
  }

  /** `public static final class Options`: `$endian`, strict mode and the root's parameters. */
  private optionsClass(out: Code, s: IrStruct, root: IrRoot, e: Emitters): void {
    const { model } = this;
    const { cls, json } = e;
    const O = model.optionsName;
    const E = cls.use("Endian");
    const C = cls.use("Canon");
    const params = optionParams(s);
    const setter = (head: string, field: string): void => {
      out.line("");
      out.block(`public ${O} ${head}`, () => {
        out.line(`this.${field} = value;`);
        out.line("return this;");
      });
    };
    out.line(
      `/** Options of {@code ${root.name}}: root parameters, {@code $endian} and strict mode. */`
    );
    out.block(`public static final class ${O}`, () => {
      out.line(`/** {@code $endian} at the root. */`);
      out.line(`public ${E} endian = ${E}.LE;`);
      out.line(`/** Strict mode: padding fill, reserved bits and bool bytes are checked. */`);
      out.line(`public boolean strict;`);
      for (const p of params) {
        out.line(`public ${model.javaValueType(p.type, true)} ${ident(p.boundName ?? p.name)};`);
      }
      setter(`endian(${E} value)`, "endian");
      setter(`strict(boolean value)`, "strict");
      for (const p of params) {
        const key = ident(p.boundName ?? p.name);
        setter(`${key}(${model.javaValueType(p.type, false)} value)`, key);
      }
      out.line("");
      out.line(
        `/** Options from canonical JSON ({@code endian}, {@code strict}, parameters by name). */`
      );
      out.block(`public static ${O} fromJson(Object json)`, () => {
        const S = model.lang("String");
        out.line(`final ${O} $o = new ${O}();`);
        out.line(`if (json == null) return $o;`);
        out.line(`final ${cls.use("Map")}<${S}, Object> $s = ${C}.objectFromJson(json);`);
        out.line(`final ${cls.use("FromJsonCtx")} $c = new ${cls.use("FromJsonCtx")}();`);
        out.line(`if ($s.get("endian") != null) $o.endian = ${E}.fromJson($s.get("endian"));`);
        out.line(`if ($s.get("strict") != null) $o.strict = ${C}.boolFromJson($s.get("strict"));`);
        for (const p of params) {
          const key = p.boundName ?? p.name;
          const j = `$s.get(${str(key)})`;
          let conv = json.valueFromJson(p.type, j, `${cls.use("ToJsonCtx")}.ptr("", ${str(key)})`);
          const b = model.javaValueType(p.type, true);
          if (model.javaValueType(p.type, false) !== b) conv = `${b}.valueOf(${conv})`;
          out.line(`if (${j} != null) $o.${ident(key)} = ${conv};`);
        }
        out.line(`return $o;`);
      });
    });
  }

  private rootApi(out: Code, s: IrStruct, root: IrRoot, e: Emitters): void {
    const model = this.model;
    const { cls, x, reader, writer } = e;
    const T = model.className(s.id);
    const O = model.optionsName;
    const E = cls.use("Endian");
    const doc = (text: string): void => {
      out.line(`/** ${text} */`);
    };
    const method = (head: string, line: string): void => {
      out.block(head, () => out.line(line));
      out.line("");
    };
    this.optionsClass(out, s, root, e);
    out.line("");

    // The root's parameters as locals, from the options `$o`.
    const prelude = (): void => {
      out.line(`final ${E} endian = $o.endian;`);
      out.line(`final boolean $le = endian == ${E}.LE;`);
      for (const p of optionParams(s)) {
        const key = ident(p.boundName ?? p.name);
        const jt = model.javaValueType(p.type, false);
        const unbox = jt !== model.javaValueType(p.type, true) ? `.${jt}Value()` : "";
        let v: string;
        if (p.default) {
          const ctx = cls.constExprCtx();
          const dv = x.to(x.compile(p.default, ctx), p.type, ctx);
          v = `$o.${key} != null ? $o.${key}${unbox} : ${dv}`;
        } else v = `${cls.use("Rt")}.req($o.${key}, ${str(p.boundName ?? p.name)})${unbox}`;
        out.line(`final ${jt} ${ident(p.name)} = ${v};`);
      }
    };
    const orDefault = `final ${O} $o = options == null ? new ${O}() : options;`;

    out.block(`private static ${T} readRoot(${cls.use("Reader")} $r, ${O} $o)`, () => {
      prelude();
      out.line(`return ${reader.rootRead(out, s)};`);
    });
    out.line("");
    out.block(
      `private static ${cls.use("LEntry")} writeRoot(${cls.use("Writer")} $w, ${T} $value, ${O} $o)`,
      () => {
        prelude();
        out.line(`return ${writer.rootWrite(out, s, "$value") ?? "null"};`);
      }
    );
    out.line("");
    const layout = s.base ? "null" : writer.regionLayout(s);
    const Api = cls.use("Api");
    const CF = cls.use("CompletableFuture");
    // Async schemas only get the async entry points (they run the blocking ones privately).
    const async = s.async;
    const vis = async ? "private" : "public";
    const parse = async ? "parseBlocking" : "parse";
    const serialize = async ? "serializeBlocking" : "serialize";
    if (!async) {
      doc("Parses {@code bytes} with default options.");
      method(`public static ${T} parse(byte[] bytes)`, `return parse(bytes, null);`);
      doc(`Parses {@code bytes}. Errors are {@link ${cls.use("YaffleException")}}s.`);
    }
    out.block(`${vis} static ${T} ${parse}(byte[] bytes, ${O} options)`, () => {
      out.line(orDefault);
      out.line(`return ${Api}.parse(bytes, $o.strict, $r -> readRoot($r, $o));`);
    });
    out.line("");
    if (!async) {
      const SR = cls.use("SafeResult");
      doc("Parses {@code bytes}, returning the error instead of throwing it.");
      method(
        `public static ${SR}<${T}> safeParse(byte[] bytes, ${O} options)`,
        `return ${SR}.of(() -> parse(bytes, options));`
      );
    }
    doc("Parses {@code bytes} on a virtual thread (async codecs complete there).");
    method(
      `public static ${CF}<${T}> parseAsync(byte[] bytes, ${O} options)`,
      `return ${Api}.async(() -> ${parse}(bytes, options));`
    );
    const AS = cls.use("AsyncSource");
    doc("Reads an async source whole, then parses it on a virtual thread.");
    method(
      `public static ${CF}<${T}> parseAsync(${AS} source, ${O} options)`,
      `return source.readAll().thenCompose(bytes -> parseAsync(bytes, options));`
    );
    if (!async) {
      doc("Serializes {@code value} with default options.");
      method(`public static byte[] serialize(${T} value)`, `return serialize(value, null);`);
      doc("Serializes {@code value}.");
    }
    out.block(`${vis} static byte[] ${serialize}(${T} value, ${O} options)`, () => {
      out.line(orDefault);
      out.line(`return ${Api}.serialize(${layout}, $w -> writeRoot($w, value, $o));`);
    });
    out.line("");
    doc("Serializes {@code value} on a virtual thread.");
    method(
      `public static ${CF}<byte[]> serializeAsync(${T} value, ${O} options)`,
      `return ${Api}.async(() -> ${serialize}(value, options));`
    );
    doc("Canonical JSON of {@code value} (docs/CONFORMANCE.md §3).");
    method(
      `public static Object toJson(${T} value)`,
      `return toJson(value, new ${cls.use("ToJsonCtx")}(), "");`
    );
    doc("A value from canonical JSON.");
    method(
      `public static ${T} fromJson(Object json)`,
      `return fromJson(json, new ${cls.use("FromJsonCtx")}(), "");`
    );
    const VR = cls.use("ViewRoot");
    const AV = cls.use("AsyncView");
    doc("A lazy view of {@code bytes} with default options (see {@link View}).");
    method(`public static View view(byte[] bytes)`, `return view(bytes, null);`);
    doc("A lazy view of {@code bytes}: fields are read on access, edits patch or re-encode.");
    method(
      `public static View view(byte[] bytes, ${O} options)`,
      `return (View) ${VR}.open(bytes, viewSpec(options));`
    );
    doc("A lazy view of a random-access source: only the blocks the view reads are loaded.");
    method(
      `public static View view(${cls.use("Source")} source, ${O} options)`,
      `return (View) ${VR}.open(source, viewSpec(options));`
    );
    doc(`An async view of an async source: accesses complete as futures (see {@link ${AV}}).`);
    method(
      `public static ${AV}<View> viewAsync(${AS} source, ${O} options)`,
      `return ${VR}.openAsync(source, viewSpec(options), View.class);`
    );
    doc("An async view of bytes in memory (for formats with async codecs).");
    method(
      `public static ${AV}<View> viewAsync(byte[] bytes, ${O} options)`,
      `return ${VR}.openAsync(bytes, viewSpec(options), View.class);`
    );
    out.block(`private static ${VR}.Spec viewSpec(${O} options)`, () => {
      out.line(orDefault);
      prelude();
      const args = s.params.map(p => ident(p.name)).join(", ");
      out.line(
        `return new ${VR}.Spec(INFO, new Object[] {${args}}, $o.strict, ${layout}, ($w, $value) -> writeRoot($w, (${T}) $value, $o));`
      );
    });
  }

  // ── enums ───────────────────────────────────────────────────────────────────

  enumFile(e: IrEnum): JavaFile {
    const model = this.model;
    const name = model.enumName(e.id);
    const cls = new ClassCtx(model, this.externs);
    const body = new Code();
    const YE = cls.use("YEnum");
    const S = model.lang("String");
    const consts = e.members.map(m => ({
      java: enumConst(e.open, m.name),
      name: m.name,
      value: longLit(BigInt.asIntN(64, BigInt(m.value)))
    }));
    const lookup = (head: string, all: string, test: string, miss: string): void => {
      body.block(`public static ${name} ${head}`, () => {
        body.line(`for (${name} e : ${all}) if (${test}) return e;`);
        body.line(`return ${miss};`);
      });
    };
    const fromJson = (rest: () => void): void => {
      body.block(`static ${name} fromJson(Object j)`, () => {
        body.block(`if (j instanceof ${S} s)`, () => {
          body.line(`final ${name} e = fromMember(s);`);
          body.line("if (e != null) return e;");
        });
        rest();
        body.line(`throw ${cls.use("Canon")}.notAMember(j);`);
      });
    };
    if (!e.open) {
      body.line(`/** The yaffle enum {@code ${e.name}} (storage {@code ${e.storage}}). */`);
      body.block(`public enum ${name} implements ${YE}`, () => {
        if (!consts.length) body.line(";");
        consts.forEach((c, i) =>
          body.line(`${c.java}(${c.value}, ${str(c.name)})${i === consts.length - 1 ? ";" : ","}`)
        );
        body.line("");
        body.line(`private static final ${name}[] ALL = values();`);
        body.line(`private final long $v;`);
        body.line(`private final ${S} $m;`);
        body.line("");
        body.block(`${name}(long value, ${S} member)`, () => {
          body.line("this.$v = value;");
          body.line("this.$m = member;");
        });
        body.line("");
        body.line("@Override");
        body.block("public long value()", () => body.line("return $v;"));
        body.line("");
        body.line("@Override");
        body.block(`public ${S} member()`, () => body.line("return $m;"));
        body.line("");
        body.line(`/** The member with this value, or null. */`);
        lookup("fromValue(long value)", "ALL", "e.$v == value", "null");
        body.line("");
        body.line(`/** The member with this yaffle name, or null. */`);
        lookup(`fromMember(${S} member)`, "ALL", "e.$m.equals(member)", "null");
        body.line("");
        body.block(`static ${name} read(long value, ${cls.use("Reader")} $r, int at)`, () => {
          const shown =
            e.storage === "u64" ? `${model.lang("Long")}.toUnsignedString(value)` : "value";
          body.line(`final ${name} e = fromValue(value);`);
          body.line(
            `if (e == null) throw $r.error(${cls.use("ErrorCode")}.CHECK, ${shown} + " is not a member of the enum", at);`
          );
          body.line("return e;");
        });
        body.line("");
        fromJson(() => {});
      });
    } else {
      body.line(
        `/** The open yaffle enum {@code ${e.name}} (storage {@code ${e.storage}}): unknown values have no member name. */`
      );
      body.block(`public record ${name}(long value, ${S} member) implements ${YE}`, () => {
        for (const c of consts) {
          body.line(
            `public static final ${name} ${c.java} = new ${name}(${c.value}, ${str(c.name)});`
          );
        }
        body.line(
          `private static final ${name}[] KNOWN = {${consts.map(c => c.java).join(", ")}};`
        );
        body.line("");
        body.line(`/** The member with this value, or an unknown value. */`);
        lookup("of(long value)", "KNOWN", "e.value == value", `new ${name}(value, null)`);
        body.line("");
        body.line(`/** The member with this yaffle name, or null. */`);
        lookup(`fromMember(${S} member)`, "KNOWN", "e.member.equals(member)", "null");
        body.line("");
        fromJson(() => {
          const P = `${cls.use("Prim")}.${e.storage.toUpperCase()}`;
          body.line(`final ${model.lang("Long")} v = ${cls.use("Canon")}.openEnumValue(j, ${P});`);
          body.line(`if (v != null) return of(v);`);
        });
      });
    }
    return { name, contents: assemble(model, cls, e.module, body.toString()) };
  }

  // ── unions ──────────────────────────────────────────────────────────────────

  unionFile(u: UnionInfo): JavaFile {
    const model = this.model;
    const cls = new ClassCtx(model, this.externs);
    const json = new JsonEmitter(model, cls, true);
    const body = new Code();
    const S = model.lang("String");
    const TJ = cls.use("ToJsonCtx");
    const C = cls.use("Canon");
    body.line(
      `/** A union value: one of ${u.variants.map(v => `{@code ${v.name}}`).join(", ")}. */`
    );
    body.block(`public sealed interface ${u.name} extends ${cls.use("YValue")}`, () => {
      u.variants.forEach((v, i) => {
        const vt = u.types[i]!;
        const java = vt.ir
          ? model.javaType(vt.type, false, true)
          : model.javaValueType(vt.type, false, true);
        body.line(`/** Variant {@code ${v.name}}. */`);
        body.line(`record ${v.java}(${java} value) implements ${u.name} {}`);
        body.line("");
      });
      body.line(`/** Canonical JSON of this value (what {@code ==} compares). */`);
      body.line("@Override");
      body.block("default Object toJsonValue()", () =>
        body.line(`return toJson(this, new ${TJ}(), "");`)
      );
      body.line("");
      body.block(`static Object toJson(${u.name} $u, ${TJ} $c, ${S} $p)`, () => {
        body.line(`return $c.obj($u, $p, ($uu, $pp) -> switch ($uu) {`);
        body.indent(() =>
          u.variants.forEach((v, i) => {
            const pv = `$v${i}`;
            const vt = u.types[i]!;
            const path = `${TJ}.ptr($pp, "value")`;
            const conv = vt.ir
              ? json.toJson(vt.type, `${pv}.value()`, path)
              : json.valueToJson(vt.type, `${pv}.value()`, path);
            body.line(`case ${v.java} ${pv} -> ${C}.union(${str(v.name)}, ${conv});`);
          })
        );
        body.line("});");
      });
      body.line("");
      body.block(
        `static ${u.name} fromJson(Object $j, ${cls.use("FromJsonCtx")} $c, ${S} $p)`,
        () => {
          body.line(`return $c.obj($j, $p, ${u.name}.class, ($jj, $pp) -> {`);
          body.indent(() => {
            body.line(`final ${cls.use("Map")}<${S}, Object> $o = ${C}.objectFromJson($jj);`);
            body.line(`final ${S} $t = ${C}.unionType($o);`);
            body.line(`final ${S} $vp = ${TJ}.ptr($pp, "value");`);
            body.line(
              `if (!java.util.Set.of(${u.variants.map(v => str(v.name)).join(", ")}).contains($t)) throw ${C}.unknownVariant($t);`
            );
            body.chain([
              [
                "try",
                () => {
                  body.line(`final ${u.name} $r = switch ($t) {`);
                  body.indent(() => {
                    u.variants.forEach((v, i) => {
                      const vt = u.types[i]!;
                      const conv = vt.ir
                        ? json.fromJson(vt.type, `$o.get("value")`, "$vp")
                        : json.valueFromJson(vt.type, `$o.get("value")`, "$vp");
                      body.line(`case ${str(v.name)} -> new ${v.java}(${conv});`);
                    });
                    body.line(`default -> throw ${C}.unknownVariant($t);`);
                  });
                  body.line("};");
                  body.line("return $c.register($pp, $r);");
                }
              ],
              [
                `catch (${cls.use("YaffleException")} $e)`,
                () => body.line(`throw $e.prefix("value");`)
              ]
            ]);
          });
          body.line("});");
        }
      );
    });
    return { name: u.name, contents: assemble(model, cls, "unions", body.toString()) };
  }
}

/** Root parameters set through the options (not `$endian` or outer bindings). */
function optionParams(s: IrStruct): IrStruct["params"] {
  return s.params.filter(p => p.origin !== "endian" && p.origin !== "outer");
}
