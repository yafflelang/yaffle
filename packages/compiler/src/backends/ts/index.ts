/**
 * TypeScript backend: IR → one TypeScript module per IR module, with typed readers, writers,
 * canonical JSON converters, views and the root API. See docs/targets/ts.md.
 */
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { IrConst, IrProgram } from "../../ir/index.ts";
import type { Backend, BackendOptions, GeneratedFile } from "../backend.ts";
import { ApiEmitter } from "./api.ts";
import { Code, ident, str } from "./code.ts";
import { ExprCompiler, formatFloat } from "./expr.ts";
import { JsonEmitter } from "./json.ts";
import { Model } from "./model.ts";
import { ModuleCtx, moduleFile, type EmitOptions } from "./module.ts";
import { ReadEmitter } from "./read.ts";
import { TypeEmitter } from "./types.ts";
import { WriteEmitter } from "./write.ts";
import { ViewEmitter } from "./view.ts";

interface TsTargetOptions {
  /** Runtime module specifier (default "@yafflelang/runtime"). */
  runtimeModule?: string;
}

/** Directory name of the inlined runtime inside the output. */
const INLINE_RUNTIME_DIR = "yaffle-runtime";

export function generateTs(input: IrProgram, options: BackendOptions): GeneratedFile[] {
  const model = new Model(input);
  const program = model.program;
  const target = (options.targetOptions ?? {}) as TsTargetOptions;
  const files: GeneratedFile[] = [];
  const emitOpts: EmitOptions = options.inlineRuntime
    ? { runtime: `${INLINE_RUNTIME_DIR}/index.ts`, runtimeRelative: true, externs: options.externs }
    : {
        runtime: target.runtimeModule ?? "@yafflelang/runtime",
        runtimeRelative: false,
        externs: options.externs
      };

  const modules = new Map<string, string>();
  for (const m of program.modules) modules.set(m.path, m.name);
  const owner = (path: string): string => {
    if (modules.has(path)) return path;
    for (const [p, n] of modules) if (n === path) return p;
    modules.set(path, path.replace(/\.yfl$/, ""));
    return path;
  };
  for (const s of program.structs) owner(s.module);
  for (const e of program.enums) owner(e.module);

  for (const [path] of modules) {
    const ctx = new ModuleCtx(model, path, emitOpts);
    const x = new ExprCompiler(model);
    const types = new TypeEmitter(model);
    types.useType = (m, n) => ctx.useType(m, n);
    const reader = new ReadEmitter(model, x, types, ctx);
    const writer = new WriteEmitter(model, x, types, ctx);
    const json = new JsonEmitter(model, types, ctx);
    const views = new ViewEmitter(model, ctx, writer);
    reader.elementEncoder = (s, t, field) =>
      field && views.derivedFrom(s).has(field) ? undefined : writer.elementEncoder(s, t);
    const api = new ApiEmitter(model, types, ctx, reader, writer, json);
    const body = new Code();
    const inModule = (m: string): boolean => owner(m) === path;

    const enums = program.enums.filter(e => inModule(e.module));
    const structs = program.structs.filter(s => inModule(s.module));
    const roots = program.roots.filter(
      r => inModule(r.module) || inModule(model.struct(r.struct).module)
    );
    const consts = program.consts.filter(c => inModule(c.module));

    for (const c of consts) body.line(constLine(c));
    if (consts.length) body.line("");
    for (const e of enums) {
      types.emitEnum(body, e.id);
      body.line("");
    }
    for (const s of structs) {
      body.line(`// ── ${s.name} ${"─".repeat(Math.max(4, 72 - s.name.length))}`);
      body.line("");
      types.emitStruct(body, s);
      body.line("");
      // Async structs (reaching an async codec) only get async readers and writers.
      reader.emitStruct(body, s, s.async);
      body.line("");
      reader.emitStruct(body, s, false, true);
      body.line("");
      writer.emitStruct(body, s, s.async);
      body.line("");
      json.emitStruct(body, s);
      body.line("");
      views.emitStruct(body, s);
      body.line("");
    }
    for (const r of roots) {
      body.line(`// ── ${r.name} (root) ${"─".repeat(Math.max(4, 64 - r.name.length))}`);
      body.line("");
      api.emitRoot(body, r);
      body.line("");
    }

    const out = new Code();
    out.line(`// Generated by yaffle from ${path}. Do not edit.`);
    out.line(`/* eslint-disable */`);
    for (const l of ctx.importLines()) out.line(l);
    out.line("");
    for (const l of ctx.hoistedLines) out.line(l);
    if (ctx.hoistedLines.length) out.line("");
    out.append(body);
    files.push({
      path: moduleFile(modules.get(path)!),
      contents:
        out
          .toString()
          .replace(/\n{3,}/g, "\n\n")
          .trimEnd() + "\n"
    });
  }

  if (options.inlineRuntime) files.push(...runtimeFiles());
  return files;
}

function constLine(c: IrConst): string {
  const v = c.value;
  let code: string;
  switch (v.kind) {
    case "int":
      code = c.type.kind === "int" && c.type.bits > 48 ? `${v.value}n` : v.value;
      break;
    case "float":
      code = formatFloat(v.value);
      break;
    case "bool":
      code = String(v.value);
      break;
    case "string":
      code = str(v.value);
      break;
    case "bytes":
      code = `$rt.fromHex(${str(v.hex)})`;
      break;
    case "endian":
      code = str(v.value);
      break;
    case "enum":
      code = str(v.member);
      break;
  }
  return `export const ${ident(c.name)} = ${code};`;
}

/** The runtime's source files, for `inlineRuntime`. */
function runtimeFiles(): GeneratedFile[] {
  const dir = runtimeSourceDir();
  const out: GeneratedFile[] = [];
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".ts") || f.endsWith(".test.ts")) continue;
    out.push({ path: `${INLINE_RUNTIME_DIR}/${f}`, contents: readFileSync(join(dir, f), "utf8") });
  }
  return out;
}

function runtimeSourceDir(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  // packages/compiler/src/backends/ts → packages/runtime/src
  const mono = join(here, "../../../../runtime/src");
  try {
    readdirSync(mono);
    return mono;
  } catch {
    const resolved = fileURLToPath(import.meta.resolve("@yafflelang/runtime"));
    return dirname(resolved);
  }
}

export const tsBackend: Backend = {
  name: "ts",
  generate(program: IrProgram, options: BackendOptions): GeneratedFile[] {
    return generateTs(program, options);
  }
};
