/**
 * Conformance adapter for the C++ target (docs/CONFORMANCE.md, conformance/src/adapter.ts):
 * generates the case directory's program into `workDir`, adds a harness that dispatches on the
 * root name, compiles it (cached by content under $YAFFLE_CPP_CACHE), runs it over the cases and
 * returns the actual JSON, bytes and error of every case; the runner re-checks them.
 *
 * Libraries the externs need are listed in the case directory's yaffle.json:
 * `targets.cpp.nixPackages` (e.g. ["zstd", "zlib"], resolved with nix-build) and
 * `targets.cpp.libs` (e.g. ["zstd", "z"]).
 */
import { execFile } from "node:child_process";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import type { IrProgram } from "../../ir/index.ts";
import { str } from "./code.ts";
import { generateCpp } from "./index.ts";
import { resolveExtern } from "./names.ts";
import { buildExecutable, findToolchain, nixPackages } from "./toolchain.ts";

// Structural copies of conformance/src/adapter.ts (the compiler package cannot import it).
export interface Case {
  name: string;
  root: string;
  args?: Record<string, unknown>;
  bytes?: string | { file: string; offset?: number; length?: number };
  json?: unknown;
  input?: unknown;
  roundtrip?: boolean | "json" | "value";
  strict?: boolean;
  error?: { phase: "parse" | "serialize"; code: string; path?: (string | number)[] };
}

export interface CaseResult {
  name: string;
  ok: boolean;
  message?: string;
  skipped?: string;
  json?: unknown;
  bytes?: string;
  error?: {
    phase: "parse" | "serialize";
    code: string;
    path?: (string | number)[];
    offset?: number;
    message?: string;
  };
}

export interface AdapterRunInput {
  caseDir: string;
  program: IrProgram;
  cases: Case[];
  workDir: string;
  externs?: Record<string, string>;
  mode?: "parse" | "view";
}

export interface ConformanceAdapter {
  target: string;
  capabilities?: { views?: boolean };
  available(): Promise<boolean>;
  run(input: AdapterRunInput): Promise<CaseResult[]>;
}

interface CppConfig {
  externs: Record<string, string>;
  nixPackages: string[];
  libs: string[];
}

/** The case directory's yaffle.json `targets.cpp` block (externs resolved to absolute paths). */
function configOf(caseDir: string): CppConfig {
  const cfg = join(caseDir, "yaffle.json");
  const out: CppConfig = { externs: {}, nixPackages: [], libs: [] };
  if (!existsSync(cfg)) return out;
  const json = JSON.parse(readFileSync(cfg, "utf8")) as {
    targets?: {
      cpp?: { externs?: Record<string, string>; nixPackages?: string[]; libs?: string[] };
    };
  };
  const t = json.targets?.cpp;
  for (const [name, spec] of Object.entries(t?.externs ?? {}))
    out.externs[name] = /^\.\.?\//.test(spec) ? resolve(dirname(cfg), spec) : spec;
  out.nixPackages = t?.nixPackages ?? [];
  out.libs = t?.libs ?? [];
  return out;
}

function runHarness(
  exe: string,
  args: string[],
  cwd: string
): Promise<{ code: number | null; stderr: string }> {
  return new Promise(res => {
    execFile(
      exe,
      args,
      { cwd, timeout: 1_800_000, maxBuffer: 64 << 20 },
      (err, _stdout, stderr) => {
        const code = err ? ((err as { code?: number }).code ?? null) : 0;
        res({ code: typeof code === "number" ? code : null, stderr: String(stderr) });
      }
    );
  });
}

/**
 * Results written so far (one JSON object per line). Decoded line by line: the results of
 * large sample files can exceed the longest string V8 can hold.
 */
function readResults(file: string): CaseResult[] {
  if (!existsSync(file)) return [];
  const buf = readFileSync(file);
  const out: CaseResult[] = [];
  let start = 0;
  for (let i = buf.indexOf(0x0a); i >= 0; i = buf.indexOf(0x0a, start)) {
    if (i > start) out.push(JSON.parse(buf.toString("utf8", start, i)) as CaseResult);
    start = i + 1;
  }
  return out;
}

export function harnessSource(
  program: IrProgram,
  header: string,
  ns: string,
  structNames: Record<string, string>
): string {
  const lines: string[] = [];
  lines.push(`// Conformance harness generated by the yaffle C++ adapter.`);
  lines.push(`#include ${str(header)}`);
  lines.push(`#include <yaffle/harness.hpp>`);
  lines.push("");
  lines.push(`int main(int argc, char** argv) {`);
  lines.push(`  std::vector<yaffle::harness::RootOps> roots;`);
  const seen = new Set<string>();
  for (const r of program.roots) {
    for (const key of [r.name, r.struct]) {
      if (seen.has(key)) continue;
      seen.add(key);
      lines.push(
        `  roots.push_back(yaffle::harness::root<${ns}::${structNames[r.struct]}>(${str(key)}));`
      );
    }
  }
  lines.push(`  return yaffle::harness::run(roots, argc, argv);`);
  lines.push(`}`);
  return lines.join("\n") + "\n";
}

export const adapter: ConformanceAdapter = {
  target: "cpp",
  capabilities: { views: true },
  async available() {
    return (await findToolchain()) !== undefined;
  },
  async run({ caseDir, program, cases, workDir, externs, mode }) {
    const tc = await findToolchain();
    if (!tc) throw new Error("not implemented: no C++ compiler");
    const cfg = configOf(caseDir);
    const ext = externs && Object.keys(externs).length ? externs : cfg.externs;
    const gen = generateCpp(program, {
      externs: ext,
      targetOptions: { namespace: "conf", file: "gen" }
    });
    mkdirSync(workDir, { recursive: true });
    for (const f of gen.files) {
      const p = join(workDir, f.path);
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, f.contents);
    }
    writeFileSync(
      join(workDir, "harness.cpp"),
      harnessSource(program, gen.header, gen.namespace, gen.structNames)
    );
    const deps: string[] = [];
    for (const [name, spec] of Object.entries(ext)) {
      const r = resolveExtern(name, spec);
      if (r.header) deps.push(r.header);
    }
    const libs = await nixPackages(cfg.nixPackages);
    libs.libs = [...cfg.libs];
    const opt = cases.some(c => typeof c.bytes === "object") ? "-O2" : "-O1";
    const exe = await buildExecutable({
      tc,
      dir: workDir,
      sources: [gen.source, "harness.cpp"],
      deps,
      libs,
      opt
    });
    const casesFile = join(workDir, "cases.json");
    writeFileSync(
      casesFile,
      JSON.stringify(mode === "view" ? cases.map(c => ({ ...c, mode: "view" })) : cases)
    );
    const resultsFile = join(workDir, "results.jsonl");
    for (let skip = 0; skip < cases.length;) {
      const r = await runHarness(exe, [casesFile, resultsFile, String(skip)], workDir);
      const got = readResults(resultsFile).length;
      if (r.code === 0 && got >= cases.length) break;
      // The harness crashed on case `got`: record it and continue after it.
      const crashed = cases[got];
      if (!crashed) break;
      const message = `harness crashed (exit ${r.code ?? "signal"}): ${r.stderr.slice(-2000)}`;
      appendFileSync(
        resultsFile,
        JSON.stringify({ name: crashed.name, ok: false, message }) + "\n"
      );
      skip = got + 1;
    }
    const byName = new Map(readResults(resultsFile).map(r => [r.name, r]));
    return cases.map(
      c => byName.get(c.name) ?? { name: c.name, ok: false, message: "no result from the harness" }
    );
  }
};
