/**
 * C++ backend: IR → one header (types and root API) and one source file (readers, writers,
 * canonical JSON, views, root API definitions) per program, over the C++20 runtime in
 * packages/runtime-cpp. See docs/targets/cpp.md.
 */
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { IrProgram } from "../../ir/index.ts";
import type { Backend, BackendOptions, GeneratedFile } from "../backend.ts";
import { ApiEmitter, constLine, emitEnumHelpers } from "./api.ts";
import { Code, ident, str } from "./code.ts";
import { ExprCompiler } from "./expr.ts";
import { JsonEmitter } from "./json.ts";
import { Model } from "./model.ts";
import { Names } from "./names.ts";
import { ReadEmitter } from "./read.ts";
import { TypeMapper } from "./types.ts";
import { ViewEmitter } from "./view.ts";
import { WriteEmitter } from "./write.ts";

export interface CppTargetOptions {
  /** Namespace of the generated code (default: derived from the root module name). */
  namespace?: string;
  /** Base name of the generated files (default: the root module's name). */
  file?: string;
  /** Generate views (default true). */
  views?: boolean;
}

/** Directory name of the inlined runtime inside the output. */
const INLINE_RUNTIME_DIR = "yaffle-runtime";

export interface CppOutput {
  files: GeneratedFile[];
  header: string;
  source: string;
  namespace: string;
  /** C++ type name of each struct, by struct id. */
  structNames: Record<string, string>;
}

export function generateCpp(input: IrProgram, options: BackendOptions): CppOutput {
  const model = new Model(input);
  const program = model.program;
  const target = (options.targetOptions ?? {}) as CppTargetOptions;
  const baseName = target.file ?? defaultBaseName(program);
  const ns = target.namespace ?? ident(baseName.replace(/[^A-Za-z0-9_]/g, "_"));
  const views = target.views !== false;
  const names = new Names(model, options.externs);
  const types = new TypeMapper(model);
  const x = new ExprCompiler(model, types);
  const reader = new ReadEmitter(model, x, types, names);
  const writer = new WriteEmitter(model, x, types, names);
  const json = new JsonEmitter(model, types, names);
  const viewer = new ViewEmitter(model, types, reader, writer);
  const api = new ApiEmitter({ model, types, names, x, reader, writer, json, views });
  const roots = new Set(program.roots.map(r => r.struct));

  // ── source: functions ──────────────────────────────────────────────────────
  const fns = new Code();
  for (const e of program.enums) emitEnumHelpers(fns, model, e.id);
  if (views) {
    for (const s of model.order) viewer.emitArgs(fns, s);
    if (model.order.length) fns.line("");
  }
  const protos: string[] = [];
  for (const s of model.order) {
    protos.push(reader.prototype(s) + ";", writer.prototype(s) + ";", ...json.prototypes(s));
    if (views) protos.push(...viewer.prototypes(s));
  }
  const bodies = fns.child();
  const viewDefs = fns.child();
  for (const s of model.order) {
    bodies.line(`// ── ${s.name} ${"─".repeat(Math.max(4, 90 - s.name.length))}`);
    bodies.line("");
    reader.emitStruct(bodies, s);
    bodies.line("");
    writer.emitStruct(bodies, s);
    bodies.line("");
    json.emitStruct(bodies, s);
    bodies.line("");
    if (views) viewer.emitFunctions(bodies, viewDefs, s);
  }
  const rootApi = fns.child();
  for (const s of model.order) if (roots.has(s.id)) api.defineRootApi(rootApi, s);

  // ── header ────────────────────────────────────────────────────────────────
  const h = new Code();
  h.line(`// Generated by yaffle. Do not edit.`);
  h.line(`#pragma once`);
  h.line("");
  h.line(`#include <yaffle/yaffle.hpp>`);
  h.line("");
  h.line(`namespace ${ns} {`);
  h.line("");
  for (const e of program.enums) {
    types.emitEnum(h, e.id);
    h.line("");
  }
  for (const s of program.structs) h.line(`struct ${model.structName(s.id)};`);
  if (views) for (const s of program.structs) h.line(`class ${viewer.viewName(s.id)};`);
  if (program.structs.length) h.line("");
  for (const c of program.consts) h.line(constLine(c, types, model));
  if (program.consts.length) h.line("");
  // Union aliases go before the first struct that uses them.
  const emittedUnions = new Set<string>();
  for (const s of model.order) {
    const decl = new Code();
    api.declareStruct(decl, s, roots.has(s.id));
    for (const u of types.unions.values()) {
      if (emittedUnions.has(u.name)) continue;
      emittedUnions.add(u.name);
      h.line(`using ${u.name} = std::variant<${u.variants.join(", ")}>;`);
      h.line("");
    }
    h.append(decl);
    h.line("");
  }
  if (views) {
    for (const s of model.order) {
      viewer.declareClass(h, s);
      h.line("");
    }
  }
  for (const r of program.roots) {
    const sname = model.structName(r.struct);
    const alias = ident(r.name);
    if (alias !== sname && !program.structs.some(s => model.structName(s.id) === alias))
      h.line(`using ${alias} = ${sname};`);
  }
  h.line(`}  // namespace ${ns}`);

  // ── source ────────────────────────────────────────────────────────────────
  const src = new Code();
  src.line(`// Generated by yaffle. Do not edit.`);
  src.line(`#include "${baseName}.hpp"`);
  for (const hdr of names.headers()) src.line(`#include ${str(hdr)}`);
  src.line("");
  src.line(`namespace ${ns} {`);
  src.line("");
  src.line(`using yaffle::i128;`);
  src.line("");
  for (const l of writer.layouts.values()) src.line(l);
  if (writer.layouts.size) src.line("");
  src.append(fns);
  for (const p of protos) src.line(`[[maybe_unused]] ${p}`);
  src.line("");
  src.append(bodies);
  src.append(viewDefs);
  src.append(rootApi);
  src.line(`}  // namespace ${ns}`);

  const header = `${baseName}.hpp`;
  const source = `${baseName}.cpp`;
  const files: GeneratedFile[] = [
    { path: header, contents: tidy(h.toString()) },
    { path: source, contents: tidy(src.toString()) }
  ];
  if (options.inlineRuntime) files.push(...runtimeFiles());
  const structNames: Record<string, string> = {};
  for (const st of program.structs) structNames[st.id] = model.structName(st.id);
  return { files, header, source, namespace: ns, structNames };
}

/**
 * Base name of the generated files: the module name for a one-module program, else the last
 * segment of the modules' common directory (`formats/demo/*.yfl` → `demo`).
 */
function defaultBaseName(program: IrProgram): string {
  const names = program.modules.map(m => m.name.split("/"));
  if (names.length === 1) return names[0]![names[0]!.length - 1] || "yaffle_gen";
  const common: string[] = [];
  for (let i = 0; names.length && names.every(n => n.length > i + 1 && n[i] === names[0]![i]); i++)
    common.push(names[0]![i]!);
  return common[common.length - 1] ?? "yaffle_gen";
}

function tidy(s: string): string {
  return s.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** The runtime's sources, for `inlineRuntime`. */
function runtimeFiles(): GeneratedFile[] {
  const root = runtimeDir();
  const out: GeneratedFile[] = [];
  for (const sub of ["include/yaffle", "src"]) {
    for (const f of readdirSync(join(root, sub))) {
      if (!/\.(hpp|cpp)$/.test(f)) continue;
      out.push({
        path: `${INLINE_RUNTIME_DIR}/${sub}/${f}`,
        contents: readFileSync(join(root, sub, f), "utf8")
      });
    }
  }
  return out;
}

/** packages/runtime-cpp in the monorepo. */
export function runtimeDir(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  return join(here, "../../../../runtime-cpp");
}

export const cppBackend: Backend = {
  name: "cpp",
  generate(program: IrProgram, options: BackendOptions): GeneratedFile[] {
    return generateCpp(program, options).files;
  }
};
