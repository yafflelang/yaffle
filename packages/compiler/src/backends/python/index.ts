/**
 * Python backend: IR → a Python package with one module per IR module. Each module holds an
 * `enum.IntEnum` per enum, a dataclass per struct (root structs get `parse`, `serialize`,
 * `to_json`, `from_json`, … methods) and imperative readers, writers, JSON converters and view
 * scanners over the pure-Python runtime `yaffle_runtime`. See docs/targets/python.md.
 */
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { IrConst, IrProgram } from "../../ir/index.ts";
import type { Backend, BackendOptions, GeneratedFile } from "../backend.ts";
import { ApiEmitter } from "./api.ts";
import { Code, pyBool, pyBytes, pyFloat, pyIdent, pyInt, pyStr } from "./code.ts";
import { ExprCompiler, detachedCtx, type ExprCtx } from "./expr.ts";
import { JsonEmitter } from "./json.ts";
import { Model } from "./model.ts";
import { ModuleCtx, type EmitOptions } from "./module.ts";
import { Names, moduleFile, moduleSegments } from "./names.ts";
import { ReadEmitter } from "./read.ts";
import { TypeEmitter } from "./types.ts";
import { emitViewInfo } from "./view.ts";
import { WriteEmitter } from "./write.ts";

export interface PythonTargetOptions {
  /** Python module the generated code imports the runtime from (default "yaffle_runtime"). */
  runtimeModule?: string;
}

/** Name of the inlined runtime package inside the output. */
const INLINE_RUNTIME_PACKAGE = "_yaffle_runtime";

export function generatePython(input: IrProgram, options: BackendOptions): GeneratedFile[] {
  const model = new Model(input);
  // Transform value types get concrete integer types from the expression compiler's ranges.
  const rangeX = new ExprCompiler(model);
  model.normalizeTransforms((e, it) => {
    const ctx: ExprCtx = {
      ...detachedCtx(() => "x"),
      field: (_n, t) => rangeX.typed("x", t),
      param: (_n, t) => rangeX.typed("x", t),
      it: () => rangeX.typed("x", it)
    };
    return rangeX.compile(e, ctx).range;
  });
  const program = model.program;
  const names = new Names(model);
  const target = (options.targetOptions ?? {}) as PythonTargetOptions;
  const emitOpts: EmitOptions = {
    externs: options.externs,
    runtime: options.inlineRuntime
      ? INLINE_RUNTIME_PACKAGE
      : (target.runtimeModule ?? "yaffle_runtime"),
    runtimeRelative: options.inlineRuntime === true
  };

  // IR module path → module name. Declarations may name their module by path or by name.
  const modules = new Map<string, string>();
  for (const m of program.modules) modules.set(m.path, m.name);
  const owner = (path: string): string => {
    if (modules.has(path)) return path;
    for (const [p, n] of modules) if (n === path) return p;
    modules.set(path, path.replace(/\.yfl$/, ""));
    return path;
  };
  for (const d of [...program.structs, ...program.enums, ...program.consts]) owner(d.module);

  const files: GeneratedFile[] = [];
  const packages = new Set<string>([""]);
  for (const [path, name] of modules) {
    const segs = moduleSegments(name);
    for (let i = 1; i < segs.length; i++) packages.add(segs.slice(0, i).join("/"));
    const contents = emitModule(model, names, path, modules, emitOpts, m => owner(m) === path);
    files.push({ path: moduleFile(name), contents });
  }
  for (const p of packages) {
    const path = p ? `${p}/__init__.py` : "__init__.py";
    if (!files.some(f => f.path === path)) {
      files.push({ path, contents: "# Generated by yaffle. Do not edit.\n" });
    }
  }
  if (options.inlineRuntime) files.push(...runtimeFiles());
  return files;
}

/** The source of the output module for IR module `path`. */
function emitModule(
  model: Model,
  names: Names,
  path: string,
  modules: Map<string, string>,
  opts: EmitOptions,
  inModule: (module: string) => boolean
): string {
  const program = model.program;
  const mod = new ModuleCtx(model, names, path, modules, opts);
  const x = new ExprCompiler(model);
  const types = new TypeEmitter(model, names, mod);
  const writer = new WriteEmitter(model, names, x, types, mod);
  const reader = new ReadEmitter(model, names, x, types, mod, writer);
  const json = new JsonEmitter(model, names, mod);
  const api = new ApiEmitter({ model, names, x, types, mod, reader, writer, json });
  const enums = program.enums.filter(e => inModule(e.module));
  const structs = program.structs.filter(s => inModule(s.module));
  const roots = program.roots.filter(r => inModule(model.struct(r.struct).module));
  const rootBy = new Map(roots.map(r => [r.struct, r]));
  const consts = program.consts.filter(c => inModule(c.module));

  const body = new Code();
  for (const c of consts) body.line(`${pyIdent(c.name)} = ${constValue(c)}`);
  if (consts.length) body.line("");
  for (const e of enums) {
    body.line("");
    types.emitEnum(body, e.id);
    body.line("");
  }
  const gap = (): void => {
    body.line("");
    body.line("");
  };
  for (const s of structs) {
    body.line("");
    body.line(`# ── ${s.name} ${"─".repeat(Math.max(4, 72 - s.name.length))}`);
    gap();
    const root = rootBy.get(s.id);
    types.emitStruct(body, s, root ? c => api.emitMethods(c, root) : undefined);
    gap();
    reader.emitStruct(body, s, s.async);
    gap();
    writer.emitStruct(body, s, s.async);
    gap();
    json.emitStruct(body, s);
    gap();
    // Scans are synchronous: async codecs in them signal the async view layer.
    reader.emitStruct(body, s, false, true);
    gap();
    emitViewInfo(body, s, model, names, writer);
    body.line("");
    if (root) {
      body.line("");
      api.emitFunctions(body, s);
    }
  }
  // Roots exported under another name than their class.
  for (const r of roots) {
    const cls = names.structClass(r.struct);
    const alias = pyIdent(r.name);
    if (alias !== cls && !names.allClassNames.has(alias)) body.line(`${alias} = ${cls}`);
  }

  const exports = [
    ...enums.map(e => names.enumClass(e.id)),
    ...structs.map(s => names.structClass(s.id)),
    ...consts.map(c => pyIdent(c.name))
  ];
  const name = modules.get(path) ?? path;
  const out = new Code();
  out.line(`# Generated by yaffle from ${path}. Do not edit.`);
  out.line(`"""${name}: generated by yaffle from ${path}."""`);
  out.line("");
  for (const l of mod.importLines()) out.line(l);
  out.line("");
  out.line(`__all__ = [${exports.map(pyStr).join(", ")}]`);
  out.line("");
  for (const l of mod.externLines()) out.line(l);
  for (const l of mod.hoistedLines) out.line(l);
  out.append(body);
  return (
    out
      .toString()
      .replace(/\n{4,}/g, "\n\n\n")
      .trimEnd() + "\n"
  );
}

function constValue(c: IrConst): string {
  const v = c.value;
  switch (v.kind) {
    case "int":
      return pyInt(BigInt(v.value));
    case "float":
      return pyFloat(v.value);
    case "bool":
      return pyBool(v.value);
    case "string":
    case "endian":
      return pyStr(v.value);
    case "bytes":
      return pyBytes(v.hex);
    case "enum":
      return pyStr(v.member);
  }
}

/** The runtime's source files, for `inlineRuntime`. */
export function runtimeFiles(): GeneratedFile[] {
  const dir = runtimeSourceDir();
  return readdirSync(dir)
    .sort()
    .filter(f => f.endsWith(".py") && !f.startsWith("_harness"))
    .map(f => ({
      path: `${INLINE_RUNTIME_PACKAGE}/${f}`,
      contents: readFileSync(join(dir, f), "utf8")
    }));
}

/** Directory of the `yaffle_runtime` package sources. */
export function runtimeSourceDir(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  return join(here, "../../../../runtime-python/yaffle_runtime");
}

/** Directory to put on PYTHONPATH so `import yaffle_runtime` works. */
export function runtimePackageRoot(): string {
  return dirname(runtimeSourceDir());
}

