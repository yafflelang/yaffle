/**
 * Rust backend: IR → Rust source using the `yaffle-runtime` crate (or an inlined copy).
 *
 * Output: one module file (`mod.rs`) with every type and its reader, writer and canonical JSON,
 * the root API, and per-IR-module re-export submodules. With `targetOptions.crate` it emits a
 * whole crate (`Cargo.toml` + `src/lib.rs`). With `inlineRuntime` the runtime sources are copied
 * in.
 *
 * Target options (yaffle.json `targets.rust`, all optional):
 * - `crate`: `{ name?: string, runtimePath?: string }`: emit a crate. `runtimePath` is the path
 *   of the `yaffle-runtime` crate relative to the output directory (ignored when inlining).
 * - `runtime`: Rust path of the runtime crate in module mode (default `::yaffle_runtime`).
 * - `fileName`: the module file name in module mode (default `mod.rs`).
 * - `views`: also generate lazy views: `X::view(bytes)` and `XView` types.
 * - `dependencies`: extra crates for the externs (`{ "zstd": "0.13" }`), added to Cargo.toml in
 *   crate mode (in module mode the including crate must have them).
 *
 * Externs (`targets.rust.externs`): a Rust path used verbatim (`crate::hash::path_hash`), or a file
 * (`./externs/zstd.rs#ZSTD`, relative to the output directory; the item defaults to the extern's
 * name). Files are mounted as modules with `#[path]` (`ext_zstd`), so they stay where they are.
 */
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { IrProgram } from "../../ir/index.ts";
import type { Backend, GeneratedFile } from "../backend.ts";
import { indent } from "./emit.ts";
import { genStructJson, genUnionJson } from "./gen-json.ts";
import { ReadGen } from "./gen-read.ts";
import { genRoot } from "./gen-root.ts";
import { genEnum, genStructDecl, genSwitchDecl, genUnionDecl } from "./gen-types.ts";
import { WriteGen } from "./gen-write.ts";
import { ViewGen, genRootView } from "./gen-view.ts";
import { Model } from "./model.ts";
import { NameSet, snake, strLit } from "./names.ts";

/** Lints generated code may trip (unused locals, naming of IR identifiers, clippy style). */
const LINTS = [
  "dead_code",
  "unused_variables",
  "unused_mut",
  "unused_parens",
  "unused_braces",
  "unused_imports",
  "unused_labels",
  "unused_assignments",
  "unreachable_patterns",
  "unreachable_code",
  "non_camel_case_types",
  "non_snake_case",
  "clippy::all"
];

/** Generates the Rust source of a program (one module). */
export function generateModule(
  program: IrProgram,
  externs: Record<string, string>,
  runtimePath: string,
  extraHeader: string[] = [],
  opts: { views?: boolean } = {}
): string {
  const m = new Model(program, externs);
  const items: string[] = [];
  for (const e of m.enums.values()) items.push(...genEnum(m, e), "");
  // Structs first: generating them registers the union types used inside them.
  const structItems: string[] = [];
  for (const sm of m.structs.values()) {
    structItems.push(...genStructDecl(m, sm), "");
    for (const sw of sm.switches) structItems.push(...genSwitchDecl(m, sm, sw), "");
    const impl = [
      ...new ReadGen(m, sm).generate(),
      ...(opts.views ? new ReadGen(m, sm, { scan: true }).generate() : []),
      ...new WriteGen(m, sm).generate(),
      ...genStructJson(m, sm)
    ];
    structItems.push(`impl ${sm.name} {`, ...indent(impl), "}", "");
    if (opts.views) structItems.push(...new ViewGen(m, sm).generate(), "");
  }
  const rootItems: string[] = [];
  for (const r of program.roots) {
    rootItems.push(...genRoot(m, r), "");
    if (opts.views) rootItems.push(...genRootView(m, r), "");
  }
  for (const u of m.unions.values()) items.push(...genUnionDecl(m, u), ...genUnionJson(m, u), "");
  items.push(...structItems, ...rootItems);

  // Re-exports per IR module.
  const modNames = new NameSet(["yaffle_runtime", "yr"]);
  const mods: string[] = [];
  for (const mod of program.modules) {
    const inMod = (x: { module?: string }) => x.module === mod.path || x.module === mod.name;
    const names = [
      ...[...m.structs.values()].filter(s => inMod(s.ir)).map(s => s.name),
      ...[...m.enums.values()].filter(e => inMod(e.ir)).map(e => e.name),
      ...program.roots.filter(inMod).map(r => m.paramsNames.get(r.struct)!)
    ];
    if (names.length === 0) continue;
    const last = mod.name.split("/").pop() ?? mod.name;
    mods.push(
      `/// Items of \`${mod.path}\`.`,
      `pub mod ${modNames.take(snake(last))} {`,
      `    pub use super::{${[...new Set(names)].join(", ")}};`,
      "}",
      ""
    );
  }

  const header = [
    "// Generated by yaffle (Rust backend). Do not edit.",
    `#![allow(${LINTS.join(", ")})]`,
    "",
    ...extraHeader,
    "use std::rc::Rc;",
    `use ${runtimePath} as yr;`,
    "use yr::ResultExt;",
    ""
  ];
  const regexes = m.regexes.map(
    (_, i) => `static RE_${i}: std::sync::OnceLock<yr::regex::Regex> = std::sync::OnceLock::new();`
  );
  return [...header, ...regexes, ...(regexes.length ? [""] : []), ...items, ...mods].join("\n");
}

const RUNTIME_DIR = new URL("../../../../runtime-rust/", import.meta.url);

/** The runtime crate's source files (for inlining), without their unit tests. */
export function runtimeSources(): { name: string; contents: string }[] {
  const dir = fileURLToPath(new URL("src/", RUNTIME_DIR));
  return readdirSync(dir)
    .filter(f => f.endsWith(".rs"))
    .sort()
    .map(f => {
      let src = readFileSync(dir + f, "utf8");
      const t = src.indexOf("#[cfg(test)]");
      if (t >= 0) src = src.slice(0, t).trimEnd() + "\n";
      return { name: f === "lib.rs" ? "mod.rs" : f, contents: src };
    });
}

/**
 * Absolute path of the runtime crate (for Cargo path dependencies). `YAFFLE_RUST_RUNTIME_DIR`
 * overrides it (e.g. a snapshot, so long test runs don't see edits made meanwhile).
 */
export function runtimeCrateDir(): string {
  const o = process.env["YAFFLE_RUST_RUNTIME_DIR"];
  if (o) return o.endsWith("/") ? o : o + "/";
  return fileURLToPath(RUNTIME_DIR);
}

export function cargoToml(
  name: string,
  runtimeDep: string | undefined,
  extraDeps: string[] = []
): string {
  const lines = [
    "[package]",
    `name = ${tomlValue(name)}`,
    'version = "0.1.0"',
    'edition = "2021"',
    "publish = false",
    "",
    "[dependencies]"
  ];
  if (runtimeDep !== undefined) lines.push(`yaffle-runtime = { path = ${tomlValue(runtimeDep)} }`);
  lines.push(...extraDeps, "");
  return lines.join("\n");
}

/** `targets.rust.dependencies` (`{ "zstd": "0.13" }`) as Cargo.toml lines. */
export function dependencyLines(deps: unknown): string[] {
  if (!deps || typeof deps !== "object") return [];
  return Object.entries(deps as Record<string, unknown>).map(([k, v]) => `${k} = ${tomlValue(v)}`);
}

function tomlValue(v: unknown): string {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `[${v.map(tomlValue).join(", ")}]`;
  if (v && typeof v === "object")
    return `{ ${Object.entries(v as Record<string, unknown>)
      .map(([k, x]) => `${k} = ${tomlValue(x)}`)
      .join(", ")} }`;
  return '""';
}

/**
 * Extern specs → Rust paths. A spec naming a file (`./externs/zstd.rs#ZSTD`) becomes the item
 * (`#ZSTD`, else the extern's name) of module `ext_<stem>` under `prefix`, one module per file;
 * `files` maps each file, as `locate` gives it, to its module. Other specs are Rust paths.
 */
export function externModules(
  externs: Record<string, string>,
  prefix: string,
  locate: (file: string) => string
): { paths: Record<string, string>; files: Map<string, string> } {
  const paths: Record<string, string> = {};
  const files = new Map<string, string>();
  const names = new NameSet();
  for (const [name, spec] of Object.entries(externs)) {
    const hash = spec.lastIndexOf("#");
    const file = hash >= 0 ? spec.slice(0, hash) : spec;
    const item = hash >= 0 ? spec.slice(hash + 1) : name;
    if (!(file.endsWith(".rs") || file.startsWith("/") || file.startsWith("."))) {
      paths[name] = spec;
      continue;
    }
    const path = locate(file);
    let mod = files.get(path);
    if (!mod) {
      const stem = path.split("/").pop()!.replace(/\.rs$/, "");
      mod = names.take("ext_" + stem.replace(/[^A-Za-z0-9_]/g, "_"));
      files.set(path, mod);
    }
    paths[name] = `${prefix}::${mod}::${item}`;
  }
  return { paths, files };
}

interface CrateOptions {
  name?: string;
  runtimePath?: string;
}

export const rustBackend: Backend = {
  name: "rust",
  generate(program, options): GeneratedFile[] {
    const to = options.targetOptions ?? {};
    const crate = to["crate"] as CrateOptions | undefined;
    const inline = options.inlineRuntime === true;
    const fileName = crate
      ? "src/lib.rs"
      : typeof to["fileName"] === "string"
        ? to["fileName"]
        : "mod.rs";
    const prefix = crate ? "crate" : "self";
    const runtime = inline
      ? `${prefix}::yaffle_runtime`
      : !crate && typeof to["runtime"] === "string"
        ? to["runtime"]
        : "::yaffle_runtime";
    // Extern files are relative to the output directory: `#[path]`s go up from the file's.
    const up = fileName
      .split("/")
      .slice(0, -1)
      .filter(Boolean)
      .map(() => "../")
      .join("");
    const ext = externModules(options.externs, prefix, file =>
      file.startsWith("/") ? file : up + file.replace(/^\.\//, "")
    );
    const header = inline ? ["pub mod yaffle_runtime;", ""] : [];
    for (const [path, mod] of ext.files)
      header.push(`#[path = ${strLit(path)}]`, `pub mod ${mod};`);
    if (ext.files.size > 0) header.push("");
    const files: GeneratedFile[] = [];
    if (crate) {
      const runtimeDep = inline ? undefined : (crate.runtimePath ?? runtimeCrateDir());
      const deps = dependencyLines(to["dependencies"]);
      files.push({
        path: "Cargo.toml",
        contents: cargoToml(crate.name ?? "yaffle_generated", runtimeDep, deps)
      });
    }
    files.push({
      path: fileName,
      contents: generateModule(program, ext.paths, runtime, header, { views: to["views"] === true })
    });
    if (inline)
      for (const s of runtimeSources())
        files.push({
          path: `${crate ? "src/" : ""}yaffle_runtime/${s.name}`,
          contents: s.contents
        });
    return files;
  }
};
