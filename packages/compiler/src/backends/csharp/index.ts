/**
 * C# backend: IR → one C# file per IR module, with a class per struct (used both as the parse
 * result and the serialize input), enums, readers, writers, canonical JSON converters and the
 * root API. See docs/targets/csharp.md.
 */
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { IrConst, IrProgram } from "../../ir/index.ts";
import type { Backend, BackendOptions, GeneratedFile } from "../backend.ts";
import { Code, ident, str, typeName } from "./code.ts";
import { ApiEmitter, DeclEmitter } from "./decls.ts";
import { ExprCompiler, formatDouble } from "./expr.ts";
import { JsonEmitter } from "./json.ts";
import { Model } from "./model.ts";
import { EXTERNS, ExternTable, IMPL, ModuleCtx } from "./module.ts";
import { ReadEmitter } from "./read.ts";
import { Types } from "./types.ts";
import { ViewEmitter } from "./views.ts";
import { WriteEmitter } from "./write.ts";

export interface CSharpTargetOptions {
  /** Namespace of the generated code (default "Yaffle.Generated"). */
  namespace?: string;
}

/** Directory name of the inlined runtime inside the output. */
const INLINE_RUNTIME_DIR = "YaffleRuntime";

const HEADER = [
  "// <auto-generated/>",
  "#nullable enable",
  "using System;",
  "using System.Collections.Generic;",
  "using System.Numerics;",
  "using System.Text.Json.Nodes;",
  "using System.Threading.Tasks;",
  "using Rt = global::Yaffle.Runtime;"
];

export function generateCSharp(program: IrProgram, options: BackendOptions): GeneratedFile[] {
  const model = new Model(program);
  const ns = ((options.targetOptions ?? {}) as CSharpTargetOptions).namespace ?? "Yaffle.Generated";
  const types = new Types(model);
  const externs = new ExternTable(model, types, options.externs);

  // Output files by module path; declarations may name a module by its name instead.
  const modules = new Map<string, string>();
  for (const m of program.modules) modules.set(m.path, m.name);
  const owner = (path: string): string => {
    if (modules.has(path)) return path;
    for (const [p, n] of modules) if (n === path) return p;
    modules.set(path, path.replace(/\.yfl$/, ""));
    return path;
  };
  for (const d of [...program.structs, ...program.enums, ...program.consts]) owner(d.module);

  const files = [...modules].map(([path, name], index) => ({
    path: `${name.replace(/^\/+/, "")}.cs`,
    contents: moduleFile(model, types, externs, ns, path, index, m => owner(m) === path)
  }));
  // Extern implementations (one class for every file), after the modules registered them.
  const ext = new Code();
  ext.line("// Extern implementations of the generated code. Generated by yaffle. Do not edit.");
  fileHeader(ext, ns);
  ext.line(`internal static class ${EXTERNS}`);
  ext.block("", () => externs.declarations().forEach(l => ext.line(l)));
  files.push({ path: `${EXTERNS}.cs`, contents: tidy(ext.toString()) });
  if (options.inlineRuntime) files.push(...runtimeFiles());
  return files;
}

function fileHeader(out: Code, ns: string): void {
  for (const l of HEADER) out.line(l);
  out.line("");
  out.line(`namespace ${ns};`);
  out.line("");
}

/** The C# file of one IR module: its types, then `YaffleImpl` with their readers, writers, …. */
function moduleFile(
  model: Model,
  types: Types,
  externs: ExternTable,
  ns: string,
  path: string,
  index: number,
  inModule: (module: string) => boolean
): string {
  const program = model.program;
  const ctx = new ModuleCtx(model, externs, index);
  const x = new ExprCompiler(model, types);
  const reader = new ReadEmitter(model, x, types, ctx);
  const writer = new WriteEmitter(model, x, types, ctx);
  const json = new JsonEmitter(model, types, ctx);
  const api = new ApiEmitter(model, types, ctx, reader, writer, json);
  const decls = new DeclEmitter(model, types, x);
  const views = new ViewEmitter(model, types, writer);

  const roots = program.roots.filter(r => inModule(model.struct(r.struct).module));
  const rootIds = new Set(roots.map(r => r.struct));
  const consts = program.consts.filter(c => inModule(c.module));

  const top = new Code();
  const impl = top.child();
  for (const e of program.enums.filter(e => inModule(e.module))) {
    decls.emitEnum(top, e.id);
    top.line("");
    decls.emitEnumHelpers(impl, e.id);
    impl.line("");
  }
  for (const s of program.structs.filter(s => inModule(s.module))) {
    const isRoot = rootIds.has(s.id);
    decls.emitStruct(top, s, isRoot ? api : undefined);
    top.line("");
    if (isRoot) {
      api.emitOptions(top, s);
      top.line("");
    }
    const name = model.className(s.id);
    impl.line(`// ── ${name} ${"─".repeat(Math.max(4, 72 - name.length))}`);
    impl.line("");
    for (const emit of [
      () => reader.emitStruct(impl, s),
      () => reader.emitStruct(impl, s, true),
      () => views.emitStruct(impl, s),
      () => writer.emitStruct(impl, s),
      () => json.emitStruct(impl, s)
    ]) {
      emit();
      impl.line("");
    }
  }
  for (const r of roots) {
    api.emitRootImpl(impl, model.struct(r.struct));
    impl.line("");
  }
  if (consts.length) {
    top.block(`public static partial class YaffleConstants`, () => {
      for (const c of consts) top.line(constLine(c, types));
    });
    top.line("");
  }

  const out = new Code();
  out.line(`// Generated by yaffle from ${path}. Do not edit.`);
  fileHeader(out, ns);
  out.append(top);
  out.line(`internal static partial class ${IMPL}`);
  out.block("", () => {
    for (const l of ctx.hoistedLines) out.line(l);
    if (ctx.hoistedLines.length) out.line("");
    out.append(impl);
  });
  return tidy(out.toString());
}

/** Trailing whitespace off, at most one blank line in a row, one final newline. */
function tidy(s: string): string {
  return (
    s
      .split("\n")
      .map(l => l.trimEnd())
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

function constLine(c: IrConst, types: Types): string {
  const v = c.value;
  const name = typeName(c.name);
  switch (v.kind) {
    case "int": {
      const cs = types.valueType(
        c.type.kind === "int" ? c.type : { kind: "int", bits: 64, signed: true }
      );
      const suffix = { ulong: "UL", long: "L", uint: "U" }[cs] ?? "";
      return `public const ${cs} ${name} = ${v.value}${suffix};`;
    }
    case "float":
      return `public const double ${name} = ${formatDouble(v.value)};`;
    case "bool":
      return `public const bool ${name} = ${v.value};`;
    case "string":
      return `public const string ${name} = ${str(v.value)};`;
    case "bytes":
      return `public static readonly byte[] ${name} = Rt.Hex.Decode(${str(v.hex)});`;
    case "endian":
      return `public const Rt.Endian ${name} = Rt.Endian.${v.value === "le" ? "Le" : "Be"};`;
    case "enum":
      return `public static readonly string ${ident(c.name)}_Member = ${str(v.member)};`;
  }
}

/** The runtime's source files, for `inlineRuntime`. */
function runtimeFiles(): GeneratedFile[] {
  const dir = runtimeSourceDir();
  return readdirSync(dir)
    .filter(f => f.endsWith(".cs") && f !== "AssemblyInfo.cs")
    .map(f => ({
      path: `${INLINE_RUNTIME_DIR}/${f}`,
      contents: readFileSync(join(dir, f), "utf8")
    }));
}

/** packages/runtime-csharp/src/Yaffle.Runtime (the runtime's C# sources). */
export function runtimeSourceDir(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  return join(here, "../../../../runtime-csharp/src/Yaffle.Runtime");
}

export const csharpBackend: Backend = {
  name: "csharp",
  generate(program: IrProgram, options: BackendOptions): GeneratedFile[] {
    return generateCSharp(program, options);
  }
};
